"""Print every reduction reason of the model 2 E2E pages, grouped by service and mechanism.

    python tools/cross_page_reductions.py [APP_DIR] > docs/cross-page-reductions.md

One line per reduction: page, card, candidate, row code, points, reason. The mechanism of a line is the row code plus
the first keyword tag that matches the reason (TAGS below); lines without a tag are grouped under the row code only.
Use the output for the cross-page check (fan-out.md, item 6; decisions.md, rule 10): the same mechanism of the same
service must have the same points on every card and page, or a written graded rule.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

APP = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "app").resolve()
sys.path.insert(0, str(APP))
import engine_app.e2e_usecases_w as w  # noqa: E402

PAGES = sorted(w.USECASES_W)  # every registered model 2 page

# (tag, regex on the reduction part of the reason). The first match wins; order from specific to general.
TAGS = [
    ("reindex / mapping change", r"reindex|mapping"),
    ("refresh delay", r"refresh"),
    ("copy rebuilt from the record", r"yeniden (kurul|oluştur|doldur|yükle|üret)|yeniden index|kopya"),
    ("change stream / CDC / pipeline", r"stream|akış|CDC|pipeline|zero-ETL|Lambda|ingestion"),
    ("one writer / primary", r"tek writer|tek primary|writer|primary"),
    ("VACUUM / MVCC / dead rows", r"VACUUM|MVCC|ölü row|silinmiş işaret"),
    ("TTL / expiry", r"TTL|expire|süre dol|silme işi|sona er"),
    ("transaction / atomicity", r"transaction|atomik|izolasyon|koşullu"),
    ("eventual / stale read", r"eventual|gecik|bayat|geride"),
    ("join / aggregate", r"JOIN|join|GROUP BY|toplam|aggregate|\$lookup"),
    ("schema / migration", r"şema|schema|ALTER|migration"),
    ("partition / hot key", r"partition|sıcak|hot"),
    ("sizing / capacity / nodes", r"boyut|kapasite|node|ACU|RPU|OCU|shard|instance|ECPU"),
    ("backup / PITR / loss", r"backup|yedek|PITR|point-in-time|kayb|kaybol|snapshot|AOF|log"),
    ("price / bill", r"fatura|ücret|ödenir|USD|dolar|saat başı|maliyet|pahalı"),
    ("application code", r"uygulama|kod|script|Lua"),
]


def reduction_part(reason):
    m = re.search(r"\d+ puan kırıldı[:.]?(.*)", reason)
    return m.group(1) if m else reason


def tag(reason):
    part = reduction_part(reason)
    for t, rx in TAGS:
        if re.search(rx, part):
            return t
    return "other"


def main():
    groups = defaultdict(list)
    for page in PAGES:
        for uc in w.USECASES_W[page]:
            for c in uc["cands"]:
                for r, (p, why) in zip(uc["rows"], uc["scores"][c]):
                    if p >= 10:
                        continue
                    text = why[1]
                    groups[(c, r["code"], tag(text))].append((page, uc["no"], uc["id"], c, r["label"], r["code"], p, text))
    print("# Cross-page reductions (model 2 E2E pages)\n")
    print("Generated by `tools/cross_page_reductions.py`. One line per reduction below 10 points: page, card, candidate, row, "
          "points, reason. Grouped by service (candidate), row code and a keyword tag of the reduction text. "
          "The same mechanism of the same service must have the same points, or the reason names a written graded rule "
          "(decisions.md, rules 2 and 10; fan-out.md, item 6).\n")
    for svc in sorted({k[0] for k in groups}):
        print(f"\n## {svc}\n")
        for key in sorted(k for k in groups if k[0] == svc):
            lines = groups[key]
            pts = sorted({ln[6] for ln in lines})
            print(f"\n### {svc} · {key[1]} · {key[2]} (points: {', '.join(map(str, pts))})\n")
            for page, no, uid, c, label, code, p, text in sorted(lines, key=lambda x: (x[6], PAGES.index(x[0]), x[1])):
                text = text.replace("|", "\\|").replace("\n", " ")
                print(f"- {page} · {no} {uid} · {c} · {label} {code} · {p} · {text}")


if __name__ == "__main__":
    main()
